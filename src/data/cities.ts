export const CITIES: City[] = RAW.map(([name, lat, lon]) => ({ name, lat, lon }))
/** Что показываем в шторке до ввода: самые частые города */
export const POPULAR_CITIES = ['Москва', 'Санкт-Петербург', 'Казань', 'Екатеринбург', 'Новосибирск', 'Краснодар', 'Нижний Новгород', 'Самара']

const norm = (s: string) => s.toLowerCase().replaceAll('ё', 'е').replace(/[^a-zа-я0-9]+/g, ' ').trim()

/** Точное совпадение названия (без учёта регистра, ё/е и дефисов) */
export function findCity(text: string): City | null {
  const q = norm(text)
  return q ? CITIES.find((c) => norm(c.name) === q) ?? null : null
}

/** Поиск по началу названия или слова: «нижн» найдёт Нижний Новгород, «ново» найдёт Новосибирск и Новороссийск */
export function searchCities(text: string, limit = 8): City[] {
  const q = norm(text)
  if (!q) return POPULAR_CITIES.map((n) => findCity(n)).filter((c): c is City => !!c).slice(0, limit)
  const starts: City[] = []
  const inside: City[] = []
  for (const c of CITIES) {
    const n = norm(c.name)
    if (n.startsWith(q)) starts.push(c)
    else if (n.split(' ').some((w) => w.startsWith(q))) inside.push(c)
  }
  return [...starts, ...inside].slice(0, limit)
}

const rad = (d: number) => (d * Math.PI) / 180
/** Расстояние по земной поверхности, км */
export function distanceKm(aLat: number, aLon: number, bLat: number, bLon: number): number {
  const dLat = rad(bLat - aLat)
  const dLon = rad(bLon - aLon)
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(rad(aLat)) * Math.cos(rad(bLat)) * Math.sin(dLon / 2) ** 2
  return 6371 * 2 * Math.asin(Math.sqrt(h))
}

/** Ближайший город из списка в радиусе maxKm: так мы называем место по геопозиции, не отправляя координаты сторонним геокодерам */
export function nearestCity(lat: number, lon: number, maxKm = 45): City | null {
  let best: City | null = null
  let bd = Infinity
  for (const c of CITIES) {
    const d = distanceKm(lat, lon, c.lat, c.lon)
    if (d < bd) { bd = d; best = c }
  }
  return best && bd <= maxKm ? best : null
}
